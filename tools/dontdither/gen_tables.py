def generate_level_data(table: InkTable) -> str:
    from dontdither.levels import FACINGS, NAME_LENGTH, LevelOp, level_filepaths, parse_level

    filepaths = level_filepaths()
    levels = [parse_level(p.read_text(), p.name) for p in filepaths]
    lines = [
        "\\ " + "=" * 74,
        "\\ level_data.asm -- GENERATED by tools/dontdither/gen_tables.py from",
        "\\ levels/*.lvl. Do not edit; regenerate with `uv run dd-build`.",
        "\\ See asm/level.asm and tools/dontdither/levels.py for the format.",
        "\\ " + "=" * 74,
        "",
        "\\ Opcodes",
        *(f"LEVEL_{op.name:<6}= {op.value}" for op in LevelOp),
        "",
        "\\ Header offsets",
        "LEVEL_HEADER_SYMMETRY = 0   \\ quarter turns between copies: 1 ROT4, 2 ROT2",
        "LEVEL_HEADER_CORE     = 1   \\ wall core ink byte",
        "LEVEL_HEADER_RIM      = 2   \\ wall rim ink byte",
        "LEVEL_HEADER_FILL     = 3   \\ ink state of open cells",
        "LEVEL_HEADER_SIZE     = 4",
        "",
        f"LEVEL_COUNT = {len(levels)}",
        f"LEVEL_NAME_LENGTH = {NAME_LENGTH}",
        "",
        "\\ Address of each level's bytecode, split into low and high bytes.",
        ".level_table_lo",
        *(f"    EQUB LO(level_{i})    \\ {lv.name}" for i, lv in enumerate(levels)),
        ".level_table_hi",
        *(f"    EQUB HI(level_{i})" for i in range(len(levels))),
        "",
        "\\ level_players: per level, the number of players, then for each of 4",
        "\\ player slots: start sx, sy (superpixels, top-left of the 6x6 footprint),",
        "\\ facing (0 = N, clockwise) and ink (0 = C, 1 = M, 2 = Y, 3 = K). Unused",
        "\\ slots are zero. LEVEL_PLAYERS_RECORD bytes per level.",
        "LEVEL_PLAYERS_RECORD = 17",
        ".level_players",
        *(
            "    EQUB " + ", ".join(
                [str(len(lv.starts()))]
                + [str(v) for st, ink in zip(lv.starts(), lv.player_inks())
                   for v in (st.sx, st.sy, st.facing, "CMYK".index(ink))]
                + ["0"] * (4 * (4 - len(lv.starts())))
            ) + f"    \\ {lv.name}"
            for lv in levels
        ),
        "",
        "\\ level_names: LEVEL_NAME_LENGTH characters per level, space padded.",
        ".level_names",
        *(f'    EQUS "{lv.name:<{NAME_LENGTH}}"' for lv in levels),
    ]
    for i, (lv, filepath) in enumerate(zip(levels, filepaths)):
        code = lv.bytecode(table)
        if len(code) > 255:
            raise ValueError(f"{filepath.name}: bytecode is {len(code)} bytes; the limit is 255")
        lines += [
            "",
            f"\\ ---- Level {i}: {lv.name} ({filepath.name}) ----",
            f".level_{i}",
            f"    EQUB {lv.symmetry.value}    \\ {lv.symmetry.name}",
            f"    EQUB WALL_INK_{lv.colouring.core}, WALL_INK_{lv.colouring.rim}"
            f"    \\ walls: {lv.colouring.core} core, {lv.colouring.rim} rim",
            f"    EQUB {table.states.index(lv.fill)}    \\ fill state {lv.fill}",
            f"    EQUB LEVEL_START, {lv.start.sx}, {lv.start.sy}, {lv.start.facing}"
            f"    \\ player 0 at ({lv.start.sx}, {lv.start.sy}) facing {FACINGS[lv.start.facing]}",
        ]
        for op, x, y in lv.commands:
            lines.append(f"    EQUB LEVEL_{op.name}, {x}, {y}")
        lines.append("    EQUB LEVEL_END")
    return "\n".join(lines) + "\n"


