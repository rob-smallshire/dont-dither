def generate_sprite_data() -> str:
    from dontdither.sprites import (
        CONTRAST_INK,
        FACINGS,
        FRAME_BYTES,
        footprint_mask_plane,
        frame_order,
        frame_planes,
        load_tank,
    )
    from dontdither.walls import full_byte

    tank = load_tank()
    lines = [
        "\\ " + "=" * 74,
        "\\ sprite_data.asm -- GENERATED by tools/dontdither/gen_tables.py from",
        "\\ sprites/tank.spr. Do not edit; regenerate with `uv run dd-build`.",
        "\\",
        "\\ One frame per facing (0 = N, clockwise) and alignment (0: even sx, sprite",
        "\\ starts at the left of a byte; 1: odd sx, 2 pixels in). Frame number =",
        "\\ facing * 2 + alignment. Each frame is SPRITE_FRAME_BYTES mask bytes and as",
        "\\ many select bytes, in drawing order: per superpixel row, the top raster",
        "\\ line's 4 bytes then the bottom line's. Mask pixels are ones where the",
        "\\ sprite is opaque; select pixels are ones where it shows the player's ink",
        "\\ (elsewhere the contrast ink).",
        "\\ " + "=" * 74,
        "",
        f"SPRITE_FRAME_BYTES = {FRAME_BYTES}",
        "SPRITE_FOOTPRINT   = 6      \\ superpixels per side",
        "",
        "\\ sprite_line_offsets: for frame byte i, the offset of its screen byte",
        "\\ from the address of the top raster line of its superpixel row:",
        "\\ byte * 8 + raster line within the row (0 top, 1 bottom).",
        ".sprite_line_offsets",
        *_byte_rows([byte * 8 + line % 2 for line, byte in frame_order()], per_row=8),
        "",
        "\\ Player ink and contrast ink bytes, indexed by ink (0 = C .. 3 = K).",
        ".ink_bytes",
        "    EQUB " + ", ".join(f"&{full_byte(i):02X}" for i in "CMYK") + "    \\ C, M, Y, K",
        ".contrast_ink_bytes",
        "    EQUB " + ", ".join(f"&{full_byte(CONTRAST_INK[i]):02X}" for i in "CMYK")
        + "    \\ " + ", ".join(CONTRAST_INK[i] for i in "CMYK"),
        "",
        "\\ footprint_mask_0 / _1: for each frame byte, ones on the pixels inside",
        "\\ the 6x6-superpixel footprint, for even (0) and odd (1) alignment. A",
        "\\ tank owns exactly these bits: restoring its background touches only",
        "\\ them, so tanks side by side sharing a byte column cannot disturb",
        "\\ each other.",
        ".footprint_mask_0",
        *_byte_rows(list(footprint_mask_plane(0)), per_row=8),
        ".footprint_mask_1",
        *_byte_rows(list(footprint_mask_plane(1)), per_row=8),
        "",
        "\\ Frame addresses, indexed by frame number.",
        ".sprite_mask_lo",
        *(f"    EQUB LO(sprite_mask_{n})" for n in range(16)),
        ".sprite_mask_hi",
        *(f"    EQUB HI(sprite_mask_{n})" for n in range(16)),
        ".sprite_select_lo",
        *(f"    EQUB LO(sprite_select_{n})" for n in range(16)),
        ".sprite_select_hi",
        *(f"    EQUB HI(sprite_select_{n})" for n in range(16)),
    ]
    for facing_number, facing in enumerate(FACINGS):
        for alignment in range(2):
            n = facing_number * 2 + alignment
            mask, select = frame_planes(tank[facing], alignment)
            lines += [
                "",
                f"\\ Frame {n}: facing {facing}, {'odd' if alignment else 'even'} sx",
                f".sprite_mask_{n}",
                *_byte_rows(list(mask), per_row=8),
                f".sprite_select_{n}",
                *_byte_rows(list(select), per_row=8),
            ]
    return "\n".join(lines) + "\n"


