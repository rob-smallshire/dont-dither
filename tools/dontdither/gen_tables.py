def generate_testcard_data(table: InkTable) -> str:
    from dontdither.screen import ARENA_CELLS
    from dontdither.testcard import (
        BORDER_COLOURING,
        SWATCH_CELLS,
        SWATCH_COLUMNS,
        swatch_colouring,
        swatch_index_of_superpixel,
        swatch_origin_cell,
        swatch_states,
        wall_cells,
    )
    from dontdither.walls import wall_bitmap

    states = swatch_states()
    columns = [swatch_index_of_superpixel(c) for c in range(ARENA_CELLS)]
    lines = [
        "\\ " + "=" * 74,
        "\\ testcard_data.asm -- GENERATED by tools/dontdither/gen_tables.py from",
        "\\ tools/dontdither/testcard.py. Do not edit; regenerate with `uv run dd-build`.",
        "\\ " + "=" * 74,
        "",
        "\\ testcard_swatch_states: ink state of each of the 6x6 swatches, row-major.",
        ".testcard_swatch_states",
    ]
    for row in range(len(states) // SWATCH_COLUMNS):
        chunk = states[row * SWATCH_COLUMNS:(row + 1) * SWATCH_COLUMNS]
        lines.append("    EQUB " + ", ".join(f"{table.states.index(s):2d}" for s in chunk)
                     + "    \\ " + " ".join("".join(map(str, s)) for s in chunk))
    lines += [
        "",
        "\\ testcard_swatch_column: swatch column (0..5) of superpixel column sx.",
        ".testcard_swatch_column",
        *_byte_rows(columns, per_row=16),
        "",
        "\\ testcard_swatch_row_base: first swatch index (row * 6) of the swatch row",
        "\\ containing superpixel row sy.",
        ".testcard_swatch_row_base",
        *_byte_rows([c * SWATCH_COLUMNS for c in columns], per_row=16),
        "",
        f"TESTCARD_BORDER_CORE = WALL_INK_{BORDER_COLOURING.core}   \\ border wall colouring",
        f"TESTCARD_BORDER_RIM  = WALL_INK_{BORDER_COLOURING.rim}",
        f"TESTCARD_SWATCH_CELLS = {SWATCH_CELLS}   \\ character cells per swatch side",
        "",
        "\\ testcard_swatch_walls: per swatch, 4 bytes: origin cell cx, cy (top-left",
        "\\ of the 5x5-cell swatch), then core and rim ink bytes for its feature.",
        "\\ The 12 (core, rim) colourings repeat three times over the 36 swatches.",
        ".testcard_swatch_walls",
        *(
            f"    EQUB {cx:2d}, {cy:2d}, WALL_INK_{c.core}, WALL_INK_{c.rim}    \\ swatch {i:2d}: {c.core} core, {c.rim} rim"
            for i in range(len(states))
            for (cx, cy), c in [(swatch_origin_cell(i), swatch_colouring(i))]
        ),
        "TESTCARD_SWATCH_RECORD = 4",
        f"TESTCARD_SWATCH_COUNT  = {len(states)}",
        "",
        "\\ testcard_walls: 32x32 wall bitmap, 4 bytes per character row, most",
        "\\ significant bit = leftmost cell.",
        ".testcard_walls",
        *_byte_rows(list(wall_bitmap(wall_cells())), per_row=4),
    ]
    return "\n".join(lines) + "\n"


