def generate_wall_tiles() -> str:
    from dontdither.walls import (
        CORNERS,
        EAST,
        NORTH,
        SOUTH,
        WEST,
        Colouring,
        full_byte,
        tile_inks,
        tile_rim_mask,
    )

    names = {NORTH: "N", EAST: "E", SOUTH: "S", WEST: "W"}
    lines = [
        "\\ " + "=" * 74,
        "\\ wall_tiles.asm -- GENERATED by tools/dontdither/gen_tables.py.",
        "\\ Do not edit; regenerate with `uv run dd-build`.",
        "\\",
        "\\ Walls occupy whole MODE 1 character cells (8x8 pixels = 4x4",
        "\\ superpixels). Each tile has a solid core and a one-pixel rim on every",
        "\\ side that does not join a neighbouring wall. The (core, rim) inks are",
        "\\ chosen per level and must differ. Tiles are stored as rim masks (rim",
        "\\ pixels all ones, core pixels zero); the screen byte for mask byte m is",
        "\\     core EOR ((core EOR rim) AND m)",
        "\\ " + "=" * 74,
        "",
        "\\ Neighbour mask bits, combined to index wall_tiles.",
        f"WALL_NORTH = {NORTH}",
        f"WALL_EAST  = {EAST}",
        f"WALL_SOUTH = {SOUTH}",
        f"WALL_WEST  = {WEST}",
        "",
        "\\ Wall inks: a screen byte of four pixels in each ink, for zp_wall_core",
        "\\ and zp_wall_rim.",
    ]
    for ink in "KCMY":
        lines.append(f"WALL_INK_{ink} = &{full_byte(ink):02X}")
    lines += [
        "",
        "\\ wall_corners: inner-corner patches, four records of five bytes:",
        "\\   arms     neighbour mask bits that must both be set",
        "\\   dx, dy   offset of the diagonal neighbour (two's complement)",
        "\\   offset   byte within the tile (0-7 left column, 8-15 right column)",
        "\\   pixel    pixel mask within that byte",
        "\\ If both arms join and the diagonal cell is not a wall, the corner pixel",
        "\\ is set to the rim ink so the outline of the inner corner is continuous.",
        ".wall_corners",
    ]
    for arms, (dx, dy), offset, pixel_mask in CORNERS:
        arm_names = "+".join(names[b] for b in (NORTH, EAST, SOUTH, WEST) if arms & b)
        lines.append(f"    EQUB {arms}, {dx & 0xFF}, {dy & 0xFF}, {offset}, &{pixel_mask:02X}"
                     f"    \\ {arm_names} corner")
    lines += [
        "WALL_CORNER_RECORD = 5",
        "WALL_CORNER_COUNT  = 4",
        "",
        "\\ wall_tiles: 16 rim masks of 16 bytes, indexed by neighbour mask * 16.",
        "\\ Each is in screen order: the left byte column's 8 raster lines, then",
        "\\ the right byte column's, so it maps straight onto a character cell.",
        "\\ In the pictures, R is rim and . is core.",
        ".wall_tiles",
    ]
    for mask in range(16):
        joined = "".join(names[b] for b in (NORTH, EAST, SOUTH, WEST) if mask & b) or "none"
        inks = tile_inks(mask, Colouring(core="K", rim="C"))
        lines.append(f"    \\ mask {mask:2d}: joins {joined}")
        for y in range(8):
            lines.append("    \\   " + "".join("." if c == "K" else "R" for c in inks[y]))
        lines += _byte_rows(list(tile_rim_mask(mask)), per_row=8)
    return "\n".join(lines) + "\n"


