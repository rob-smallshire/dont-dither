# Screen geometry tables
# ---------------------------------------------------------------------------

def generate_screen_tables() -> str:
    from dontdither.screen import ARENA_CELLS, superpixel_address

    addresses = [superpixel_address(0, sy) for sy in range(ARENA_CELLS)]
    lines = [
        "\\ " + "=" * 74,
        "\\ screen_tables.asm -- GENERATED by tools/dontdither/gen_tables.py.",
        "\\ Do not edit; regenerate with `uv run dd-build`.",
        "\\ " + "=" * 74,
        "",
        "\\ superpixel_row_lo / _hi: address of the top raster byte of superpixel",
        "\\ (0, sy), indexed by sy = 0..127:",
        "\\     &3000 + (sy DIV 4) * 640 + (sy AND 3) * 2",
        "\\ Superpixel (sx, sy) is at that address + (sx DIV 2) * 8; the bottom",
        "\\ raster byte is the next address. For a character row cy, entry 4*cy is",
        "\\ the address of the row's first character cell.",
        ".superpixel_row_lo",
        *_byte_rows([a & 0xFF for a in addresses], per_row=16),
        ".superpixel_row_hi",
        *_byte_rows([a >> 8 for a in addresses], per_row=16),
        "",
        "\\ bit_masks: bit_masks?n selects bit (7 - n); used to test column n of a",
        "\\ bitmap byte whose most significant bit is the leftmost cell.",
        ".bit_masks",
        "    EQUB &80, &40, &20, &10, &08, &04, &02, &01",
    ]
    return "\n".join(lines) + "\n"


