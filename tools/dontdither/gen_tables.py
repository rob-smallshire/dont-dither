NO_PARENT = 0x7F
PAINTS_FLAG = 0x80


def generate_paint_data(table: InkTable) -> str:
    from dontdither.game import FIRE_PERIOD
    from dontdither.splats import SPLATS_FILEPATH, parse_splats, ray_tree

    splats = parse_splats(SPLATS_FILEPATH.read_text(), SPLATS_FILEPATH.name)
    variants = len(splats["E"])
    trees = [(base, v, ray_tree(splats[base][v])) for base in ("E", "NE") for v in range(variants)]
    max_nodes = max(len(t) for _, _, t in trees)

    state_of_counts = [0xFF] * 125
    for i, (c, m, y, k) in enumerate(table.states):
        state_of_counts[c * 25 + m * 5 + y] = i

    lines = [
        "\\ " + "=" * 74,
        "\\ paint_data.asm -- GENERATED by tools/dontdither/gen_tables.py from",
        "\\ tools/dontdither/game.py, the ink table and sprites/splats.spr. Do not",
        "\\ edit; regenerate with `uv run dd-build`.",
        "\\ " + "=" * 74,
        "",
        f"FIRE_PERIOD    = {FIRE_PERIOD}   \\ ticks between shots while fire is held",
        f"SPLAT_VARIANTS = {variants}   \\ variants per facing, cycled per shot",
        f"SPLAT_MAX_NODES = {max_nodes}  \\ most nodes in any splat tree",
        "",
        "\\ state_counts: the ink counts of each state, 4 bytes per state in the",
        "\\ order C, M, Y, K. Index = state * 4 + ink.",
        ".state_counts",
        *(f"    EQUB {c}, {m}, {y}, {k}    \\ {i:2d}" for i, (c, m, y, k) in enumerate(table.states)),
        "",
        "\\ state_index_of: for each state, C * 25 + M * 5 + Y, its index into",
        "\\ state_of_counts. Moving one quantum from ink v to ink p changes the",
        "\\ index by ink_weight[p] - ink_weight[v].",
        ".state_index_of",
        *_byte_rows([c * 25 + m * 5 + y for c, m, y, k in table.states], per_row=16),
        ".ink_weight",
        "    EQUB 25, 5, 1, 0    \\ C, M, Y, K",
        "",
        "\\ state_of_counts: the state with counts (C, M, Y, K), indexed by",
        "\\ C * 25 + M * 5 + Y (K is 4 - C - M - Y). Unused entries are &FF.",
        ".state_of_counts",
        *_byte_rows(state_of_counts, per_row=25),
        "",
        "\\ Splat trees (see tools/dontdither/splats.py): the cells on the lines",
        "\\ from the tank's footprint centre to each splat cell, parents before",
        "\\ children. Three bytes per node:",
        "\\   dx, dy   cell offset from the footprint's top-left superpixel, two's",
        "\\            complement, for facing E (tree 0..) or NE (tree SPLAT_VARIANTS..);",
        "\\            other facings rotate it: (x, y) -> (5 - y, x) per quarter turn",
        f"\\   parent   index of the parent node, or &{NO_PARENT:02X} for none; bit 7 set",
        "\\            if the node is a splat cell to paint (else only passed over)",
        "\\ A node is blocked if its cell is a wall or outside the arena, or its",
        "\\ parent is blocked; unblocked splat cells are painted.",
        f"SPLAT_NO_PARENT = &{NO_PARENT:02X}",
        f"SPLAT_PAINTS    = &{PAINTS_FLAG:02X}",
        "SPLAT_NODE_BYTES = 3",
        ".splat_tree_lo",
        *(f"    EQUB LO(splat_tree_{i})" for i in range(len(trees))),
        ".splat_tree_hi",
        *(f"    EQUB HI(splat_tree_{i})" for i in range(len(trees))),
        ".splat_tree_nodes",
        "    EQUB " + ", ".join(str(len(t)) for _, _, t in trees),
    ]
    for i, (base, v, tree) in enumerate(trees):
        lines += ["", f"\\ Tree {i}: facing {base}, variant {v + 1}", f".splat_tree_{i}"]
        for n, node in enumerate(tree):
            dx, dy = node.cell
            parent = NO_PARENT if node.parent < 0 else node.parent
            flag = PAINTS_FLAG if node.paints else 0
            lines.append(f"    EQUB &{dx & 0xFF:02X}, &{dy & 0xFF:02X}, &{parent | flag:02X}"
                         f"    \\ {n:2d}: ({dx:3d}, {dy:3d}) parent {node.parent:3d}{' paint' if node.paints else ''}")
    return "\n".join(lines) + "\n"


