def generate_hud_font() -> str:
    from dontdither.hud_font import DIGITS, GLYPH_ROWS, glyph_bytes

    lines = [
        "\\ " + "=" * 74,
        "\\ hud_font.asm -- GENERATED by tools/dontdither/gen_tables.py from",
        "\\ tools/dontdither/hud_font.py. Do not edit; regenerate with `uv run dd-build`.",
        "\\",
        "\\ A 3x5 digit font: GLYPH_ROWS bytes per digit, each one MODE 1 byte of",
        "\\ four pixels (three for the glyph, one gap) with all-ones pixels where",
        "\\ the glyph is set. AND with a colour byte to draw it in that colour.",
        "\\ " + "=" * 74,
        "",
        f"GLYPH_ROWS = {GLYPH_ROWS}",
        ".hud_digits",
    ]
    for digit in "0123456789":
        glyph = DIGITS[digit]
        lines.append("    EQUB " + ", ".join(f"&{b:02X}" for b in glyph_bytes(glyph))
                     + f"    \\ {digit}: " + " ".join(glyph))
    return "\n".join(lines) + "\n"


